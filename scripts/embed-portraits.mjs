import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../assets/avatars/", import.meta.url);
const files = readdirSync(dir)
  .filter((name) => /^anime-\d+\.webp$/.test(name))
  .sort((a, b) => Number(a.match(/\d+/)[0]) - Number(b.match(/\d+/)[0]));
const uris = files.map(
  (name) =>
    `  "data:image/webp;base64,${readFileSync(new URL(name, dir)).toString("base64")}",`,
);
writeFileSync(
  new URL("../lib/portraits.ts", import.meta.url),
  `// Generated by scripts/embed-portraits.mjs from assets/avatars. Do not edit.\nexport const PORTRAITS = [\n${uris.join("\n")}\n] as const;\n`,
);
